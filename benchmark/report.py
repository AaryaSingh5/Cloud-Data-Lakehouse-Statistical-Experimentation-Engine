"""Results report (9.5): mean ± std per profile, paired tests, held-day penalty sensitivity, pooled section."""
from __future__ import annotations

from collections import defaultdict
from pathlib import Path

from benchmark import scoring
from benchmark.scoring import mean_std, paired_pvalues

RESULTS_PATH = Path(__file__).resolve().parents[1] / "docs" / "results.md"

METRICS = (
    "detection_precision", "detection_recall", "detection_f1",
    "coverage", "revenue_error", "orders_error",
    "wrong_published_days", "revenue_error_all_days",
    "duplicate_rows", "run_seconds",
)
PROPOSED_ONLY = {"detection_precision", "detection_recall", "detection_f1"}

FETCH_SQL = "SELECT seed, profile, arm, metric, value FROM benchmark_results"
DAYS_SQL = "SELECT seed, profile, arm, published, pred_revenue, truth_revenue FROM benchmark_days"


def _cell(values) -> str:
    mean, std = mean_std(values)
    return "n/a" if mean is None else f"{mean:.4g} ± {std:.2g}"


def _p(value) -> str:
    return "n<3" if value is None else f"{value:.3f}"


def _aligned(data, metric, profile=None):
    """Proposed and baseline values paired by (profile, seed)."""
    a, b = [], []
    for prof in sorted({k[0] for k in data}):
        if profile is not None and prof != profile:
            continue
        p = data.get((prof, "proposed", metric), {})
        q = data.get((prof, "baseline", metric), {})
        for seed in sorted(set(p) & set(q)):
            a.append(p[seed])
            b.append(q[seed])
    return a, b


def _table(data, profile=None) -> list[str]:
    lines = [
        "| metric | proposed | baseline | p (t-test) | p (Wilcoxon) |",
        "|---|---|---|---|---|",
    ]
    for metric in METRICS:
        proposed = [v for (prof, arm, m), seeds in data.items()
                    if m == metric and arm == "proposed" and (profile in (None, prof))
                    for v in seeds.values()]
        baseline = [v for (prof, arm, m), seeds in data.items()
                    if m == metric and arm == "baseline" and (profile in (None, prof))
                    for v in seeds.values()]
        base_cell = "–" if metric in PROPOSED_ONLY else _cell(baseline)
        a, b = ([], []) if metric in PROPOSED_ONLY else _aligned(data, metric, profile)
        t_p, w_p = paired_pvalues(a, b)
        lines.append(f"| {metric} | {_cell(proposed)} | {base_cell} | {_p(t_p)} | {_p(w_p)} |")
    return lines


def _sensitivity(runs, profile=None) -> list[str]:
    """Revenue error on all truth days, for each held-day penalty, paired by run."""
    lines = [
        "| held-day penalty | proposed | baseline | p (t-test) | p (Wilcoxon) |",
        "|---|---|---|---|---|",
    ]
    keys = sorted({(p, s) for (p, s, _arm) in runs if profile in (None, p)})
    for penalty in scoring.SENSITIVITY_PENALTIES:
        prop, base = [], []
        for prof, seed in keys:
            pr = runs.get((prof, seed, "proposed"))
            br = runs.get((prof, seed, "baseline"))
            if not pr or not br:
                continue
            prop.append(scoring.penalty_error(pr, penalty))
            base.append(scoring.penalty_error(br, penalty))
        t_p, w_p = paired_pvalues(prop, base)
        lines.append(f"| {penalty} | {_cell(prop)} | {_cell(base)} | {_p(t_p)} | {_p(w_p)} |")
    return lines


def write_report(conn, path: Path = RESULTS_PATH) -> Path:
    with conn.cursor() as cur:
        cur.execute(FETCH_SQL)
        rows = cur.fetchall()
        cur.execute(DAYS_SQL)
        day_rows = cur.fetchall()

    data: dict = defaultdict(dict)
    for seed, profile, arm, metric, value in rows:
        data[(profile, arm, metric)][seed] = value

    runs: dict = defaultdict(list)
    for seed, profile, arm, published, pred_rev, truth_rev in day_rows:
        runs[(profile, seed, arm)].append(
            {"published": published, "pred_revenue": pred_rev, "truth_revenue": truth_rev}
        )

    lines = [
        "# Benchmark results",
        "",
        "Generated by `python -m benchmark.run`. Values are mean ± standard deviation across seeds.",
        "Paired p-values compare the proposed platform with the baseline on the same seed.",
        "With three seeds per profile, these tests have little power. The pooled section uses all runs.",
        "The held-day penalty sensitivity shows how the revenue-error verdict depends on the penalty",
        "given to a day that was not published. The baseline publishes every day, so only the proposed",
        "platform is affected by the penalty.",
        "",
    ]
    if not rows:
        lines.append("No results yet.")
    else:
        for profile in sorted({k[0] for k in data}):
            lines += [f"## Fault profile: {profile}", ""] + _table(data, profile) + [""]
            lines += ["### Held-day penalty sensitivity", ""] + _sensitivity(runs, profile) + [""]
        lines += ["## All profiles pooled", ""] + _table(data) + [""]
        lines += ["### Held-day penalty sensitivity (pooled)", ""] + _sensitivity(runs) + [""]

    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path